#!/usr/bin/env node
// Builds plugins/harness-loops/workflows/develop-spec.js from workflow-src/develop-spec.js with develop-phase's loop
// inlined as a function. A workflow can run another one only one level deep, and the project wrapper already
// spends that level, so develop-spec cannot call develop-phase with workflow(): it carries the same code instead,
// and this build keeps that code one source. `--check` exits 1 when the built file is stale (validate.js runs it).
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const LOOPS = path.join(ROOT, 'plugins', 'harness-loops');
const PHASE = path.join(LOOPS, 'workflows', 'develop-phase.js');
const SRC = path.join(LOOPS, 'workflow-src', 'develop-spec.js');
const OUT = path.join(LOOPS, 'workflows', 'develop-spec.js');
const MARK = '/* @inline develop-phase */';

function build() {
  const phase = fs.readFileSync(PHASE, 'utf8');
  const meta = phase.match(/^export const meta = \{[\s\S]*?\n\}\n/m);
  if (!meta) throw new Error(`${path.relative(ROOT, PHASE)}: no top-level \`export const meta = {…}\` block to strip`);
  const body = phase.slice(meta.index + meta[0].length).trim();
  const src = fs.readFileSync(SRC, 'utf8');
  if (src.split(MARK).length !== 2) throw new Error(`${path.relative(ROOT, SRC)}: needs exactly one ${MARK} line`);
  // The body is pasted as written, not re-indented: its prompts are template literals, and indenting them would
  // change what every seat reads.
  const fn = [
    '// GENERATED by scripts/build-workflows.js — edit workflow-src/develop-spec.js or workflows/develop-phase.js, then',
    '// run `node scripts/build-workflows.js`. validate.js fails while this copy is stale.',
    '// develop-phase\'s loop, verbatim, as a function: its top-level `return` becomes the function\'s.',
    'async function developPhase(args, agent, log, phase) {',
    body,
    '}',
  ].join('\n');
  // A function, not a string: a `$&` or `$'` in the loop's code would otherwise be read as a replacement pattern.
  return src.replace(MARK, () => fn);
}

if (require.main === module) {
  const out = build();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== out) {
      console.error(`${path.relative(ROOT, OUT)} is stale — run: node scripts/build-workflows.js`);
      process.exit(1);
    }
    process.exit(0);
  }
  if (current !== out) fs.writeFileSync(OUT, out);
  console.log(`${path.relative(ROOT, OUT)} ${current === out ? 'already current' : 'written'}`);
}

module.exports = { build, OUT, SRC, PHASE };
